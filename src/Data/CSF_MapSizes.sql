-- 本模组的机制是：把本局【已有的】城邦玩家送下地图保持休眠，玩家再用建邦
-- 使节把它们放上地图。所以：
--
--     可建数量 = 本局城邦总数 T − 地图上保留数 N
--                （T 由 MapSizes 决定，N 由 CSF_KEEP_ACTIVE_ON_MAP 决定）
--
-- 官方 MapSizes.xml 的 MaxCityStates（= 开局设置里能拉到的上限）：
--     Duel 6 / Tiny 10 / Small 14 / Standard 18 / Large 22 / Huge 24
